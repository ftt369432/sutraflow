import React, { useState, useEffect } from 'react';
import { Tag, Zap, X, Settings, RefreshCw } from 'lucide-react';
import { Button } from '../ui/Button';
import { Card, CardContent, CardHeader, CardTitle } from '../ui/Card';
import { Switch } from '../ui/Switch';
import { Label } from '../ui/Label';
import { EmailMessage } from '../../services/email/types';
import { EmailTaggingService } from '../../services/email/EmailTaggingService';
import { toast } from 'sonner';
import { cn } from '../../lib/utils';

interface AutoTaggingControlProps {
  emails: EmailMessage[];
  onEmailsTagged: (emails: EmailMessage[]) => void;
  isAutoTaggingEnabled: boolean;
  onToggleAutoTagging: (enabled: boolean) => void;
  className?: string;
}

export function AutoTaggingControl({
  emails,
  onEmailsTagged,
  isAutoTaggingEnabled,
  onToggleAutoTagging,
  className
}: AutoTaggingControlProps) {
  const [taggingService] = useState(() => new EmailTaggingService());
  const [isProcessing, setIsProcessing] = useState(false);
  const [processedCount, setProcessedCount] = useState(0);
  const [showSettings, setShowSettings] = useState(false);
  const [lastProcessed, setLastProcessed] = useState<Date | null>(null);
  const [tagStats, setTagStats] = useState({
    totalTags: 0,
    autoTags: 0,
    manualTags: 0,
    averageConfidence: 0
  });

  useEffect(() => {
    calculateTagStats();
  }, [emails]);

  const calculateTagStats = () => {
    let totalTags = 0;
    let autoTags = 0;
    let manualTags = 0;
    let confidenceSum = 0;

    emails.forEach(email => {
      if (email.tags) {
        totalTags += email.tags.length;
        email.tags.forEach(tag => {
          if (tag.autoGenerated) {
            autoTags++;
          } else {
            manualTags++;
          }
          confidenceSum += tag.confidence;
        });
      }
    });

    setTagStats({
      totalTags,
      autoTags,
      manualTags,
      averageConfidence: totalTags > 0 ? confidenceSum / totalTags : 0
    });
  };

  const processAllEmails = async () => {
    setIsProcessing(true);
    setProcessedCount(0);

    try {
      const taggedEmails = [...emails];
      
      for (let i = 0; i < taggedEmails.length; i++) {
        const email = taggedEmails[i];
        
        // Skip if already has auto-generated tags
        const hasAutoTags = email.tags?.some(tag => tag.autoGenerated);
        if (hasAutoTags) {
          setProcessedCount(i + 1);
          continue;
        }

        // Analyze and tag the email
        const suggestedTags = await taggingService.analyzeAndTagEmail(email);
        
        // Add tags to email
        if (!email.tags) {
          email.tags = [];
        }
        
        // Remove old auto-generated tags and add new ones
        email.tags = email.tags.filter(tag => !tag.autoGenerated);
        email.tags.push(...suggestedTags);

        setProcessedCount(i + 1);
        
        // Small delay to show progress
        await new Promise(resolve => setTimeout(resolve, 50));
      }

      onEmailsTagged(taggedEmails);
      setLastProcessed(new Date());
      
      toast.success(`Successfully tagged ${taggedEmails.length} emails with auto-generated tags`);
    } catch (error) {
      console.error('Auto-tagging failed:', error);
      toast.error('Failed to auto-tag emails. Please try again.');
    } finally {
      setIsProcessing(false);
      setProcessedCount(0);
    }
  };

  const reprocessEmail = async (email: EmailMessage) => {
    try {
      const suggestedTags = await taggingService.analyzeAndTagEmail(email);
      
      // Update email tags
      if (!email.tags) {
        email.tags = [];
      }
      
      // Remove old auto-generated tags and add new ones
      email.tags = email.tags.filter(tag => !tag.autoGenerated);
      email.tags.push(...suggestedTags);

      // Update the emails array
      const updatedEmails = emails.map(e => e.id === email.id ? email : e);
      onEmailsTagged(updatedEmails);
      
      toast.success(`Re-tagged email: ${email.subject}`);
    } catch (error) {
      console.error('Failed to re-tag email:', error);
      toast.error('Failed to re-tag email');
    }
  };

  const clearAutoTags = () => {
    const clearedEmails = emails.map(email => ({
      ...email,
      tags: email.tags?.filter(tag => !tag.autoGenerated) || []
    }));
    
    onEmailsTagged(clearedEmails);
    toast.success('Cleared all auto-generated tags');
  };

  const untaggedEmails = emails.filter(email => 
    !email.tags || email.tags.length === 0 || !email.tags.some(tag => tag.autoGenerated)
  );

  return (
    <Card className={cn("w-full", className)}>
      <CardHeader className="pb-3">
        <CardTitle className="flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Zap className="h-5 w-5 text-purple-600" />
            Auto-Tagging
          </div>
          <Button
            variant="ghost"
            size="sm"
            onClick={() => setShowSettings(!showSettings)}
          >
            <Settings className="h-4 w-4" />
          </Button>
        </CardTitle>
      </CardHeader>
      <CardContent className="space-y-4">
        {/* Auto-tagging Toggle */}
        <div className="flex items-center justify-between">
          <div className="space-y-1">
            <Label htmlFor="auto-tagging">Enable Auto-Tagging</Label>
            <p className="text-xs text-gray-600 dark:text-gray-400">
              Automatically tag new emails as they arrive
            </p>
          </div>
          <Switch
            id="auto-tagging"
            checked={isAutoTaggingEnabled}
            onCheckedChange={onToggleAutoTagging}
          />
        </div>

        {/* Stats */}
        <div className="grid grid-cols-2 gap-3">
          <div className="text-center p-2 bg-gray-50 dark:bg-gray-800 rounded">
            <div className="text-lg font-bold text-purple-600">{tagStats.totalTags}</div>
            <div className="text-xs text-gray-600 dark:text-gray-400">Total Tags</div>
          </div>
          <div className="text-center p-2 bg-gray-50 dark:bg-gray-800 rounded">
            <div className="text-lg font-bold text-blue-600">{tagStats.autoTags}</div>
            <div className="text-xs text-gray-600 dark:text-gray-400">Auto-Generated</div>
          </div>
        </div>

        {/* Process All Button */}
        <div className="space-y-2">
          <Button
            onClick={processAllEmails}
            disabled={isProcessing || emails.length === 0}
            className="w-full"
          >
            {isProcessing ? (
              <>
                <RefreshCw className="h-4 w-4 mr-2 animate-spin" />
                Tagging... ({processedCount}/{emails.length})
              </>
            ) : (
              <>
                <Tag className="h-4 w-4 mr-2" />
                Tag All Emails ({untaggedEmails.length} untagged)
              </>
            )}
          </Button>
          
          {lastProcessed && (
            <p className="text-xs text-gray-600 dark:text-gray-400 text-center">
              Last processed: {lastProcessed.toLocaleTimeString()}
            </p>
          )}
        </div>

        {/* Settings Panel */}
        {showSettings && (
          <div className="border-t pt-4 space-y-3">
            <h4 className="font-medium text-sm">Auto-Tagging Settings</h4>
            
            <div className="space-y-2">
              <div className="flex items-center justify-between">
                <Label className="text-sm">Confidence Threshold</Label>
                <span className="text-sm text-gray-600">70%</span>
              </div>
              
              <div className="flex items-center justify-between">
                <Label className="text-sm">Max Tags per Email</Label>
                <span className="text-sm text-gray-600">5</span>
              </div>
              
              <div className="flex items-center justify-between">
                <Label className="text-sm">Average Confidence</Label>
                <span className="text-sm text-gray-600">
                  {Math.round(tagStats.averageConfidence * 100)}%
                </span>
              </div>
            </div>

            <div className="flex gap-2">
              <Button
                variant="outline"
                size="sm"
                onClick={clearAutoTags}
                className="flex-1"
              >
                <X className="h-4 w-4 mr-1" />
                Clear Auto Tags
              </Button>
            </div>
          </div>
        )}

        {/* Progress Indicator */}
        {isProcessing && (
          <div className="space-y-2">
            <div className="w-full bg-gray-200 dark:bg-gray-700 rounded-full h-2">
              <div
                className="bg-purple-600 h-2 rounded-full transition-all duration-300"
                style={{ width: `${(processedCount / emails.length) * 100}%` }}
              />
            </div>
            <p className="text-xs text-center text-gray-600 dark:text-gray-400">
              Processing email {processedCount} of {emails.length}
            </p>
          </div>
        )}

        {/* Quick Actions for Recent Emails */}
        {!isProcessing && untaggedEmails.slice(0, 3).length > 0 && (
          <div className="space-y-2">
            <h4 className="font-medium text-sm">Quick Tag Recent Emails</h4>
            {untaggedEmails.slice(0, 3).map(email => (
              <div key={email.id} className="flex items-center justify-between p-2 bg-gray-50 dark:bg-gray-800 rounded">
                <div className="flex-1 min-w-0">
                  <p className="text-sm font-medium truncate">{email.subject}</p>
                  <p className="text-xs text-gray-600 dark:text-gray-400 truncate">{email.from}</p>
                </div>
                <Button
                  variant="ghost"
                  size="sm"
                  onClick={() => reprocessEmail(email)}
                  className="ml-2"
                >
                  <Zap className="h-3 w-3" />
                </Button>
              </div>
            ))}
          </div>
        )}
      </CardContent>
    </Card>
  );
}
