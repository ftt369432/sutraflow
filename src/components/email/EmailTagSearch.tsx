import React, { useState, useEffect } from 'react';
import { Search, Tag, X, Filter, Plus, Hash } from 'lucide-react';
import { Input } from '../ui/Input';
import { Button } from '../ui/Button';
import { Badge } from '../ui/Badge';
import { Card, CardContent, CardHeader, CardTitle } from '../ui/Card';
import { EmailTag } from '../../services/email/types';
import { EmailTaggingService } from '../../services/email/EmailTaggingService';
import { cn } from '../../lib/utils';

interface EmailTagSearchProps {
  availableTags: EmailTag[];
  selectedTags: string[];
  onTagsChange: (tags: string[]) => void;
  onCreateTag?: (tag: Omit<EmailTag, 'id' | 'confidence' | 'autoGenerated'>) => void;
  className?: string;
}

export function EmailTagSearch({
  availableTags,
  selectedTags,
  onTagsChange,
  onCreateTag,
  className
}: EmailTagSearchProps) {
  const [searchTerm, setSearchTerm] = useState('');
  const [showCreateTag, setShowCreateTag] = useState(false);
  const [newTagName, setNewTagName] = useState('');
  const [newTagCategory, setNewTagCategory] = useState<EmailTag['category']>('custom');
  const [newTagColor, setNewTagColor] = useState('#6366f1');
  const [filteredTags, setFilteredTags] = useState<EmailTag[]>(availableTags);

  const tagColors = [
    '#ef4444', '#f59e0b', '#eab308', '#22c55e', '#06b6d4', 
    '#3b82f6', '#6366f1', '#8b5cf6', '#d946ef', '#ec4899'
  ];

  useEffect(() => {
    if (!searchTerm) {
      setFilteredTags(availableTags);
    } else {
      const filtered = availableTags.filter(tag =>
        tag.name.toLowerCase().includes(searchTerm.toLowerCase()) ||
        tag.category.toLowerCase().includes(searchTerm.toLowerCase())
      );
      setFilteredTags(filtered);
    }
  }, [searchTerm, availableTags]);

  const handleTagSelect = (tagName: string) => {
    if (selectedTags.includes(tagName)) {
      onTagsChange(selectedTags.filter(t => t !== tagName));
    } else {
      onTagsChange([...selectedTags, tagName]);
    }
  };

  const handleCreateTag = () => {
    if (newTagName.trim() && onCreateTag) {
      onCreateTag({
        name: newTagName.trim(),
        category: newTagCategory,
        color: newTagColor,
        description: `Custom ${newTagCategory} tag`
      });
      setNewTagName('');
      setShowCreateTag(false);
    }
  };

  const groupTagsByCategory = (tags: EmailTag[]) => {
    const grouped: Record<string, EmailTag[]> = {};
    tags.forEach(tag => {
      if (!grouped[tag.category]) {
        grouped[tag.category] = [];
      }
      grouped[tag.category].push(tag);
    });
    return grouped;
  };

  const categoryIcons = {
    legal: '⚖️',
    priority: '🔥',
    type: '📄',
    client: '👥',
    status: '📊',
    calendar: '📅',
    custom: '🏷️'
  };

  const groupedTags = groupTagsByCategory(filteredTags);

  return (
    <Card className={cn("w-full max-w-md", className)}>
      <CardHeader className="pb-3">
        <CardTitle className="flex items-center gap-2 text-base">
          <Filter className="h-4 w-4" />
          Filter by Tags
        </CardTitle>
      </CardHeader>
      <CardContent className="space-y-4">
        {/* Search Input */}
        <div className="relative">
          <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 text-gray-400 h-4 w-4" />
          <Input
            placeholder="Search tags..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            className="pl-10"
          />
        </div>

        {/* Selected Tags */}
        {selectedTags.length > 0 && (
          <div className="space-y-2">
            <h4 className="text-sm font-medium text-gray-700 dark:text-gray-300 flex items-center gap-1">
              <Hash className="h-3 w-3" />
              Active Filters ({selectedTags.length})
            </h4>
            <div className="flex flex-wrap gap-1">
              {selectedTags.map(tagName => {
                const tag = availableTags.find(t => t.name === tagName);
                return (
                  <Badge
                    key={tagName}
                    className="flex items-center gap-1 cursor-pointer"
                    style={{ backgroundColor: tag?.color + '20', color: tag?.color, borderColor: tag?.color + '50' }}
                    onClick={() => handleTagSelect(tagName)}
                  >
                    {tagName}
                    <X className="h-3 w-3" />
                  </Badge>
                );
              })}
            </div>
          </div>
        )}

        {/* Available Tags by Category */}
        <div className="space-y-3 max-h-64 overflow-y-auto">
          {Object.entries(groupedTags).map(([category, tags]) => (
            <div key={category}>
              <h4 className="text-xs font-medium text-gray-600 dark:text-gray-400 uppercase tracking-wider mb-2 flex items-center gap-1">
                <span>{categoryIcons[category as keyof typeof categoryIcons]}</span>
                {category} ({tags.length})
              </h4>
              <div className="flex flex-wrap gap-1">
                {tags.map(tag => (
                  <Badge
                    key={tag.id}
                    className={cn(
                      "cursor-pointer transition-all text-xs",
                      selectedTags.includes(tag.name)
                        ? "ring-2 ring-offset-1 ring-blue-500"
                        : "hover:scale-105"
                    )}
                    style={{ 
                      backgroundColor: tag.color + '20', 
                      color: tag.color, 
                      borderColor: tag.color + '50' 
                    }}
                    onClick={() => handleTagSelect(tag.name)}
                    title={tag.description}
                  >
                    {tag.name}
                    {tag.autoGenerated && (
                      <span className="ml-1 text-xs opacity-60">⚡</span>
                    )}
                  </Badge>
                ))}
              </div>
            </div>
          ))}
        </div>

        {/* Create New Tag */}
        {onCreateTag && (
          <div className="border-t pt-3">
            {!showCreateTag ? (
              <Button
                variant="outline"
                size="sm"
                onClick={() => setShowCreateTag(true)}
                className="w-full"
              >
                <Plus className="h-4 w-4 mr-2" />
                Create Custom Tag
              </Button>
            ) : (
              <div className="space-y-2">
                <Input
                  placeholder="Tag name"
                  value={newTagName}
                  onChange={(e) => setNewTagName(e.target.value)}
                  size="sm"
                />
                <div className="flex gap-2">
                  <select
                    value={newTagCategory}
                    onChange={(e) => setNewTagCategory(e.target.value as EmailTag['category'])}
                    className="flex-1 px-2 py-1 text-sm border rounded"
                  >
                    <option value="custom">Custom</option>
                    <option value="legal">Legal</option>
                    <option value="priority">Priority</option>
                    <option value="type">Type</option>
                    <option value="client">Client</option>
                    <option value="status">Status</option>
                    <option value="calendar">Calendar</option>
                  </select>
                  <div className="flex gap-1">
                    {tagColors.slice(0, 5).map(color => (
                      <button
                        key={color}
                        className={cn(
                          "w-6 h-6 rounded border-2",
                          newTagColor === color ? "border-gray-800" : "border-gray-300"
                        )}
                        style={{ backgroundColor: color }}
                        onClick={() => setNewTagColor(color)}
                      />
                    ))}
                  </div>
                </div>
                <div className="flex gap-2">
                  <Button
                    size="sm"
                    onClick={handleCreateTag}
                    disabled={!newTagName.trim()}
                    className="flex-1"
                  >
                    Create
                  </Button>
                  <Button
                    variant="outline"
                    size="sm"
                    onClick={() => {
                      setShowCreateTag(false);
                      setNewTagName('');
                    }}
                  >
                    Cancel
                  </Button>
                </div>
              </div>
            )}
          </div>
        )}

        {/* Clear All */}
        {selectedTags.length > 0 && (
          <Button
            variant="outline"
            size="sm"
            onClick={() => onTagsChange([])}
            className="w-full"
          >
            Clear All Filters
          </Button>
        )}
      </CardContent>
    </Card>
  );
}
