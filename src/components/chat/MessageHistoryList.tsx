import React from 'react';
import { Bot, Wrench, FileText, ExternalLink, ShieldAlert, Sparkles } from 'lucide-react';
import { cn } from '@/lib/utils';
import { Avatar, AvatarImage, AvatarFallback } from '@/components/ui/Avatar';
import { MarkdownMessage } from '@/components/ai/MarkdownMessage';
import { NeuralThinking } from '@/components/ai/NeuralThinking';
import { useAttachedDriveStore } from '@/store';
import type { Message, AIAssistant } from '@/types/ai';

const LEGAL_FOOTER_NOTICE = "[Notice: Preliminary research and calculation draft generated by California Workers' Comp MCP Engine. For legal/claims practitioner review only. Must be independently verified before formal citation, negotiation, or WCAB filing.]";

const formatLegalToolName = (tool: string): string => {
  const t = tool.toLowerCase();
  if (t.includes('calculate_lien_penalties') || t.includes('penalty')) return 'LC § 5814 Penalty Audit';
  if (t.includes('calculate_omfs') || t.includes('med_legal')) return 'OMFS Legal-Medical Fee Audit';
  if (t.includes('courtlistener') || t.includes('case_law')) return 'WCAB Precedent Search';
  if (t.includes('california_labor_code')) return 'Labor Code Authority Check';
  if (t.includes('depo_phone') || t.includes('transcript')) return 'Deposition Transcript Analysis';
  if (t.includes('icd10')) return 'ICD-10 Diagnostic Classification';
  if (t.includes('tax_optimization')) return 'Entity Tax Structure Analysis';
  if (t.includes('shell') || t.includes('python')) return 'Deterministic Legal Engine';
  return tool
    .replace(/_/g, ' ')
    .replace(/^(search|get|create|find|fetch|run|analyze)/, (m) => m.charAt(0).toUpperCase() + m.slice(1));
};

const extractDocumentInfo = (content: string) => {
  const lines = content.split('\n');
  const titleLine = lines.find(l => l.trim().startsWith('# '));
  const isPleading = content.includes("WORKERS' COMPENSATION APPEALS BOARD") ||
                     content.includes("STATE OF CALIFORNIA") ||
                     content.includes("PETITION FOR") ||
                     content.includes("TRIAL BRIEF") ||
                     content.includes("POINTS AND AUTHORITIES") ||
                     content.includes("CASE NO:");
                     
  if (titleLine || (isPleading && content.length > 400)) {
    const rawTitle = titleLine ? titleLine.replace(/^#\s*/, '').trim() : 'Legal Pleading / Research Document';
    const words = content.trim().split(/\s+/).length;
    return {
      title: rawTitle,
      wordCount: words,
      content
    };
  }
  return null;
};

const getAssistantThinkingAction = (assistant: AIAssistant | null) => {
  if (!assistant) return 'is thinking...';
  const name = (assistant.name || '').toLowerCase();
  const cat = (assistant.category || assistant.type || '').toLowerCase();
  if (name.includes('creative') || cat.includes('creator') || cat.includes('creative')) {
    return 'is ideating & crafting creative strategy';
  }
  if (name.includes('medi') || cat.includes('medical') || cat.includes('health')) {
    return 'is analyzing clinical research & medical databases';
  }
  if (name.includes('legal') || cat.includes('legal')) {
    return 'is analyzing statutory authorities & case law';
  }
  return 'is processing your request';
};

const getAssistantBadge = (assistant: AIAssistant | null) => {
  if (!assistant) return 'AI Engine';
  const name = (assistant.name || '').toLowerCase();
  const cat = (assistant.category || assistant.type || '').toLowerCase();
  if (name.includes('creative') || cat.includes('creator') || cat.includes('creative')) {
    return 'Creative & Marketing Suite';
  }
  if (name.includes('medi') || cat.includes('medical') || cat.includes('health')) {
    return 'Medical Research Engine';
  }
  if (name.includes('legal') || cat.includes('legal')) {
    return "Workers' Comp Engine";
  }
  return assistant.category || 'Intelligence Engine';
};

const TypingIndicator = ({ selectedAssistant }: { selectedAssistant: AIAssistant | null }) => (
  <div className="flex gap-3 animate-in fade-in duration-300 py-3">
    {selectedAssistant && (
      <Avatar className="h-7 w-7 mt-0.5 border shadow-xs shrink-0">
        {selectedAssistant.avatar ? (
          <AvatarImage src={selectedAssistant.avatar} alt={selectedAssistant.name} />
        ) : (
          <AvatarFallback className="bg-indigo-600/10 text-indigo-600 dark:text-indigo-400">
            <Bot className="h-4 w-4" />
          </AvatarFallback>
        )}
      </Avatar>
    )}
    <div className="flex-1 max-w-2xl">
      <div className="px-4 py-2.5 rounded-lg border border-border/40 bg-muted/30 dark:bg-zinc-900/40 flex items-center gap-2">
        <span className="text-xs text-muted-foreground font-medium">
          {selectedAssistant?.name || 'AI Assistant'} {getAssistantThinkingAction(selectedAssistant)}
        </span>
        <div className="flex space-x-1 ml-1">
          <div className="w-1.5 h-1.5 rounded-full bg-indigo-500 animate-bounce" />
          <div className="w-1.5 h-1.5 rounded-full bg-indigo-500 animate-bounce delay-100" />
          <div className="w-1.5 h-1.5 rounded-full bg-indigo-500 animate-bounce delay-200" />
        </div>
      </div>
    </div>
  </div>
);

export interface MessageHistoryListProps {
  messages: Message[];
  selectedAssistant: AIAssistant | null;
  user: any;
  isLoading: boolean;
  isTyping: boolean;
  messagesEndRef: React.RefObject<HTMLDivElement>;
  getUserInitials: () => string;
  onAlternativeSelect?: (alternative: string) => void;
  onOpenDocument?: (doc: { title: string; content: string }) => void;
}

export const MessageHistoryList: React.FC<MessageHistoryListProps> = ({
  messages,
  selectedAssistant,
  user,
  isLoading,
  isTyping,
  messagesEndRef,
  getUserInitials,
  onAlternativeSelect,
  onOpenDocument
}) => {
  const addGeneratedDocument = useAttachedDriveStore((s) => s.addGeneratedDocument);

  const handleDocumentOpen = (title: string, content: string) => {
    // 1. Sync immediately to the GenieDrive store under "AI Generated Docs & Brain"
    addGeneratedDocument(title, content);

    // 2. Open in Canvas / Sovereign Viewer if callback provided
    if (onOpenDocument) {
      onOpenDocument({ title, content });
    }
  };

  return (
    <div className="space-y-6">
      {messages.map((message) => {
        if (message.role === 'user') {
          return (
            <div key={message.id} className="flex justify-end w-full">
              <div className="max-w-[85%] rounded-xl px-4 py-3 bg-muted/40 dark:bg-zinc-800/50 border border-border/50 text-foreground text-sm shadow-xs">
                <div className="flex items-center gap-2 mb-1.5 text-[11px] font-semibold text-muted-foreground uppercase tracking-wider">
                  <Avatar className="h-4 w-4 border">
                    {user?.user_metadata?.avatar_url ? (
                      <AvatarImage src={user.user_metadata.avatar_url} />
                    ) : (
                      <AvatarFallback className="text-[9px] bg-primary/10 text-primary">
                        {getUserInitials()}
                      </AvatarFallback>
                    )}
                  </Avatar>
                  <span>You</span>
                </div>
                <div className="prose prose-sm dark:prose-invert max-w-none">
                  <MarkdownMessage content={message.content} />
                </div>
              </div>
            </div>
          );
        }

        // Assistant Message (Cursor/Antigravity style flat stream)
        const thinkMatch = message.content.match(/<think>([\s\S]*?)<\/think>/i);
        let thinking = thinkMatch ? thinkMatch[1].trim() : (message.content.includes('<think>') && !message.content.includes('</think>') ? message.content.split('<think>')[1] : null);

        if (!thinking) {
          const finalMatch = message.content.match(/<final>([\s\S]*?)<\/final>/i);
          if (finalMatch) {
            const finalRaw = finalMatch[1].trim();
            const rMatch = finalRaw.match(/"reasoning":\s*"([\s\S]*?)"/i);
            if (rMatch) {
              thinking = rMatch[1];
            } else {
              try {
                const finalJson = JSON.parse(finalRaw);
                if (finalJson.reasoning) thinking = finalJson.reasoning;
              } catch (_e) {}
            }
          }
        }

        const finalContent = message.content
          .replace(/<think>([\s\S]*?)<\/think>/gi, '')
          .replace(/<think>[\s\S]*/gi, '')
          .replace(/<final>[\s\S]*?<\/final>/gi, '')
          .trim();

        const docInfo = extractDocumentInfo(finalContent);
        const hasFooter = finalContent.includes("Preliminary research and calculation draft");

        return (
          <div key={message.id} className="flex gap-3 w-full animate-in fade-in duration-300">
            <Avatar className="h-7 w-7 mt-1 border shadow-xs shrink-0">
              {selectedAssistant?.avatar ? (
                <AvatarImage src={selectedAssistant.avatar} alt={selectedAssistant.name} />
              ) : (
                <AvatarFallback className="bg-indigo-600/10 text-indigo-600 dark:text-indigo-400">
                  <Bot className="h-4 w-4" />
                </AvatarFallback>
              )}
            </Avatar>

            <div className="flex-1 min-w-0 space-y-3">
              {/* Header */}
              <div className="flex items-center gap-2">
                <span className="text-xs font-bold text-foreground">
                  {selectedAssistant?.name || 'AI Assistant'}
                </span>
                <span className="text-[10px] text-muted-foreground font-medium px-1.5 py-0.2 rounded bg-muted/60 dark:bg-zinc-800 border border-border/40">
                  {getAssistantBadge(selectedAssistant)}
                </span>
              </div>

              {/* Point-by-Point Thought Stream with Chevron */}
              {thinking && (
                <NeuralThinking
                  content={thinking}
                  isStreaming={isLoading && messages[messages.length - 1].id === message.id && !message.content.includes('</think>')}
                />
              )}

              {/* Document Artifact Card (if document generated) */}
              {docInfo && (
                <div className="flex items-center justify-between p-3 rounded-lg border border-indigo-500/30 bg-indigo-500/5 hover:bg-indigo-500/10 transition-colors my-2">
                  <div className="flex items-center gap-2.5 min-w-0 mr-3">
                    <div className="p-2 rounded-md bg-indigo-500/10 text-indigo-500 shrink-0">
                      <FileText className="h-4 w-4" />
                    </div>
                    <div className="min-w-0">
                      <h4 className="text-xs font-bold text-foreground truncate">{docInfo.title}</h4>
                      <p className="text-[11px] text-muted-foreground">
                        {docInfo.wordCount} words • {selectedAssistant?.name?.toLowerCase().includes('legal') ? 'California 28-Line Pleading Format' : 'Executive Document Format'}
                      </p>
                    </div>
                  </div>
                  <button
                    onClick={() => handleDocumentOpen(docInfo.title, docInfo.content)}
                    className="px-2.5 py-1.5 text-xs font-semibold bg-indigo-600 hover:bg-indigo-500 text-white rounded-md transition-all flex items-center gap-1.5 shrink-0 shadow-xs cursor-pointer"
                  >
                    <ExternalLink className="h-3 w-3" />
                    <span>Open in Sovereign Viewer</span>
                  </button>
                </div>
              )}

              {/* Synthesized Markdown Response */}
              {finalContent && (
                <div className="prose prose-sm dark:prose-invert max-w-none text-foreground leading-relaxed">
                  <MarkdownMessage content={finalContent} />
                </div>
              )}

              {/* Tools Used (Context-Aware Verbiage) */}
              {message.metadata?.toolsUsed && message.metadata.toolsUsed.length > 0 && (
                <div className="flex flex-wrap items-center gap-1.5 pt-2 border-t border-border/30">
                  <span className="text-[10px] font-semibold text-muted-foreground flex items-center gap-1 uppercase tracking-wider mr-1">
                    <Wrench className="h-3 w-3" /> {selectedAssistant?.name?.toLowerCase().includes('legal') ? 'Legal Verification:' : 'Execution Verification:'}
                  </span>
                  {message.metadata.toolsUsed.map((tool, idx) => (
                    <span
                      key={idx}
                      className="inline-flex items-center px-2 py-0.5 rounded-full text-[10px] font-medium bg-indigo-500/10 border border-indigo-500/20 text-indigo-400"
                    >
                      {formatLegalToolName(tool)}
                    </span>
                  ))}
                </div>
              )}

              {/* Suggested Options */}
              {message.metadata?.alternatives && message.metadata.alternatives.length > 0 && (
                <div className="pt-2 border-t border-border/30 space-y-1.5">
                  <p className="text-[10px] font-semibold text-muted-foreground uppercase tracking-wider">Suggested Next Actions:</p>
                  <div className="flex flex-col gap-1.5">
                    {message.metadata.alternatives.map((option: string, idx: number) => (
                      <button
                        key={idx}
                        onClick={() => onAlternativeSelect?.(option)}
                        className="text-left w-full px-3 py-2 text-xs rounded-lg border border-indigo-500/20 bg-indigo-500/5 hover:bg-indigo-500/15 hover:border-indigo-500/40 text-indigo-300 transition-all cursor-pointer focus:outline-none"
                      >
                        {option}
                      </button>
                    ))}
                  </div>
                </div>
              )}

              {/* Mandatory California Workers' Comp Notice Footer (Only for Legal Persona) */}
              {!hasFooter && finalContent && (selectedAssistant?.name?.toLowerCase().includes('legal') || selectedAssistant?.type === 'legal' || message.metadata?.isLegal) && (
                <div className="pt-2 border-t border-border/20 text-[10px] text-muted-foreground/70 italic flex items-center gap-1.5">
                  <ShieldAlert className="h-3 w-3 shrink-0 text-amber-500/70" />
                  <span>{LEGAL_FOOTER_NOTICE}</span>
                </div>
              )}
            </div>
          </div>
        );
      })}

      {isTyping && <TypingIndicator selectedAssistant={selectedAssistant} />}
      <div ref={messagesEndRef} />
    </div>
  );
};

