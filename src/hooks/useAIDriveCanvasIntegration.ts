/**
 * 🔗 AI Drive Canvas Integration Hook
 * 
 * Connects the AdvancedCanvasEditor with AI Drive for centralized document management
 * Provides seamless editing experience with AI Drive as the document hub
 */

import { useState, useCallback, useEffect } from 'react';
import { AdvancedCanvasDocument } from '../components/canvas/AdvancedCanvasEditor';
// import { useAIDrive } from './useAIDrive'; // Will be implemented
import { v4 as uuidv4 } from 'uuid';

export interface AIDriveCanvasState {
  documents: AdvancedCanvasDocument[];
  activeDocumentId: string | null;
  isLoading: boolean;
  autoSaveEnabled: boolean;
  lastSaved: Date | null;
}

export interface AIDriveCanvasActions {
  openDocumentInEditor: (documentId: string) => void;
  createNewDocument: (template?: string, contentType?: string, customTitle?: string) => string;
  updateDocumentContent: (documentId: string, content: string) => void;
  updateDocumentTitle: (documentId: string, title: string) => void;
  closeDocument: (documentId: string) => void;
  saveToAIDrive: (documentId: string) => Promise<void>;
  loadFromAIDrive: (fileId: string) => Promise<void>;
  refreshDocuments: () => Promise<void>;
  addDocument: (document: AdvancedCanvasDocument) => void;
  exportDocument: (documentId: string, format: 'pdf' | 'docx' | 'txt') => void;
  enableAutoSave: (enabled: boolean) => void;
}

/**
 * 🎯 Main AI Drive Canvas Integration Hook
 * 
 * This hook provides centralized document management through AI Drive
 * while maintaining the advanced canvas editing capabilities
 */
export function useAIDriveCanvasIntegration(userId?: string): {
  state: AIDriveCanvasState;
  actions: AIDriveCanvasActions;
} {
  // Document State
  const [documents, setDocuments] = useState<AdvancedCanvasDocument[]>([]);
  const [activeDocumentId, setActiveDocumentId] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [autoSaveEnabled, setAutoSaveEnabled] = useState(true);
  const [lastSaved, setLastSaved] = useState<Date | null>(null);

  // AI Drive Integration (placeholder - will be implemented)
  const aiDriveFiles: any[] = [];
  const createFile = async (fileData: any) => {
    console.log('📁 AI Drive: Creating file', fileData.name);
    // Implementation will be added when AI Drive hook is available
  };
  const updateFile = async (fileId: string, data: any) => {
    console.log('📁 AI Drive: Updating file', fileId);
  };
  const deleteFile = async (fileId: string) => {
    console.log('📁 AI Drive: Deleting file', fileId);
  };
  const loadFile = async (fileId: string) => {
    console.log('📁 AI Drive: Loading file', fileId);
    return null;
  };

  // Template Content Generator
  const getTemplateContent = useCallback((template: string = 'blank', contentType: string = 'document') => {
    const timestamp = new Date().toLocaleDateString();
    
    switch (template) {
      case 'business':
        return `# Business Document

**Date**: ${timestamp}
**Subject**: 

## Executive Summary

[Provide a brief overview of the document's purpose...]

## Main Content

[Begin your business document content here...]

---
*Document created with GenieFlow AI*`;

      case 'legal':
        return `# Legal Document

## Case Information
- **Case Title**: 
- **Case Number**: 
- **Court**: 
- **Date**: ${timestamp}

## Document Content

[Begin your legal document here...]

---
*This document was created using GenieFlow AI*`;

      case 'letter':
        return `# Letter

**Date**: ${timestamp}
**To**: [Recipient]
**From**: [Your Name]

Dear [Recipient],

[Letter content goes here...]

Sincerely,
[Your Name]

---
*Generated by GenieFlow AI*`;

      default:
        return `# New Document

**Created**: ${timestamp}

[Start writing your content here...]

---
*Document created with GenieFlow AI*`;
    }
  }, []);

  // Auto-save functionality
  useEffect(() => {
    if (!autoSaveEnabled) return;

    const autoSaveInterval = setInterval(() => {
      documents.forEach(doc => {
        if (doc.id === activeDocumentId && doc.content) {
          saveToAIDrive(doc.id).catch(console.error);
        }
      });
    }, 30000); // Auto-save every 30 seconds

    return () => clearInterval(autoSaveInterval);
  }, [documents, activeDocumentId, autoSaveEnabled]);

  // Actions Implementation
  const openDocumentInEditor = useCallback((documentId: string) => {
    console.log('🎯 Opening document in editor:', documentId);
    setActiveDocumentId(documentId);
  }, []);

  const createNewDocument = useCallback((template: string = 'blank', contentType: string = 'document', customTitle?: string) => {
    // Generate a more descriptive title
    let documentTitle = customTitle;
    if (!documentTitle) {
      const timestamp = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
      switch (template) {
        case 'legal':
          documentTitle = `Legal Document - ${timestamp}`;
          break;
        case 'business':
          documentTitle = `Business Document - ${timestamp}`;
          break;
        case 'letter':
          documentTitle = `Letter - ${timestamp}`;
          break;
        default:
          documentTitle = `Document - ${timestamp}`;
      }
    }

    const newDocument: AdvancedCanvasDocument = {
      id: uuidv4(),
      title: documentTitle,
      content: getTemplateContent(template, contentType),
      contentType: contentType as any,
      isActive: true,
      lastModified: new Date(),
      metadata: {
        wordCount: 0,
        aiGenerated: false,
        version: 1
      }
    };

    setDocuments(prev => [
      ...prev.map(doc => ({ ...doc, isActive: false })),
      newDocument
    ]);
    setActiveDocumentId(newDocument.id);

    return newDocument.id;
  }, [getTemplateContent]);

  const updateDocumentContent = useCallback((documentId: string, content: string) => {
    setDocuments(prev => prev.map(doc => 
      doc.id === documentId 
        ? { 
            ...doc, 
            content, 
            lastModified: new Date(),
            metadata: {
              ...doc.metadata,
              wordCount: content.split(' ').length
            }
          }
        : doc
    ));
  }, []);

  const updateDocumentTitle = useCallback((documentId: string, title: string) => {
    setDocuments(prev => prev.map(doc => 
      doc.id === documentId 
        ? { ...doc, title, lastModified: new Date() }
        : doc
    ));
  }, []);

  const closeDocument = useCallback((documentId: string) => {
    setDocuments(prev => {
      const remaining = prev.filter(doc => doc.id !== documentId);
      
      // If closing active document, switch to another
      if (documentId === activeDocumentId) {
        const nextActive = remaining.length > 0 ? remaining[0].id : null;
        setActiveDocumentId(nextActive);
      }
      
      return remaining;
    });
  }, [activeDocumentId]);

  const saveToAIDrive = useCallback(async (documentId: string) => {
    const document = documents.find(doc => doc.id === documentId);
    if (!document) return;

    setIsLoading(true);
    try {
      await createFile({
        name: document.title,
        content: document.content,
        type: document.contentType,
        metadata: {
          canvasDocumentId: document.id,
          ...document.metadata
        }
      });
      
      setLastSaved(new Date());
      console.log('📁 Document saved to AI Drive:', document.title);
    } catch (error) {
      console.error('❌ Failed to save to AI Drive:', error);
    } finally {
      setIsLoading(false);
    }
  }, [documents, createFile]);

  const loadFromAIDrive = useCallback(async (fileId: string) => {
    setIsLoading(true);
    try {
      const file = await loadFile(fileId);
      if (file) {
        const loadedDocument: AdvancedCanvasDocument = {
          id: file.metadata?.canvasDocumentId || uuidv4(),
          title: file.name,
          content: file.content,
          contentType: file.type as any || 'document',
          isActive: true,
          lastModified: file.lastModified || new Date(),
          metadata: {
            wordCount: file.content.split(' ').length,
            aiGenerated: file.metadata?.aiGenerated || false,
            version: file.metadata?.version || 1
          }
        };

        setDocuments(prev => [
          ...prev.map(doc => ({ ...doc, isActive: false })),
          loadedDocument
        ]);
        setActiveDocumentId(loadedDocument.id);
        
        console.log('📁 Document loaded from AI Drive:', file.name);
      }
    } catch (error) {
      console.error('❌ Failed to load from AI Drive:', error);
    } finally {
      setIsLoading(false);
    }
  }, [loadFile]);

  const exportDocument = useCallback((documentId: string, format: 'pdf' | 'docx' | 'txt') => {
    const doc = documents.find(d => d.id === documentId);
    if (!doc) return;

    // Create download link
    const content = doc.content;
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    
    const link = window.document.createElement('a');
    link.href = url;
    link.download = `${doc.title}.${format}`;
    link.click();
    
    URL.revokeObjectURL(url);
    
    console.log('📄 Document exported:', doc.title, format);
  }, [documents]);

  const enableAutoSave = useCallback((enabled: boolean) => {
    setAutoSaveEnabled(enabled);
  }, []);

  const refreshDocuments = useCallback(async () => {
    if (!userId) {
      console.warn('🔒 Cannot refresh documents: No user ID provided');
      return;
    }

    try {
      setIsLoading(true);
      console.log('🔄 Refreshing AI Drive canvas documents...');
      
      // TODO: Integrate with actual AI Drive service when available
      // For now, keep existing documents and add any new ones from MultiCanvasController
      
      // Trigger a state update to force canvas refresh
      setDocuments(current => [...current]);
      
      console.log('✅ Documents refreshed successfully');
    } catch (error) {
      console.error('❌ Failed to refresh documents:', error);
      throw error;
    } finally {
      setIsLoading(false);
    }
  }, [userId]);

  const addDocument = useCallback((document: AdvancedCanvasDocument) => {
    console.log('📄 Adding document to AI Drive Canvas:', document.title, 'ID:', document.id);
    
    setDocuments(current => {
      // Check if document already exists
      const existsIndex = current.findIndex(doc => doc.id === document.id);
      if (existsIndex >= 0) {
        // Update existing document
        const updated = [...current];
        updated[existsIndex] = { ...updated[existsIndex], ...document };
        console.log('📄 Updated existing document:', document.title);
        return updated;
      } else {
        // Add new document
        console.log('📄 Added new document to canvas:', document.title);
        return [...current, document];
      }
    });
    
    // 🎯 CRITICAL FIX: Auto-select the newly added document
    setTimeout(() => {
      console.log(`🎯 Auto-selecting new document: ${document.title} (${document.id})`);
      setActiveDocumentId(document.id);
    }, 100);
  }, []);

  return {
    state: {
      documents,
      activeDocumentId,
      isLoading,
      autoSaveEnabled,
      lastSaved
    },
    actions: {
      openDocumentInEditor,
      createNewDocument,
      updateDocumentContent,
      updateDocumentTitle,
      closeDocument,
      saveToAIDrive,
      loadFromAIDrive,
      refreshDocuments,
      addDocument,
      exportDocument,
      enableAutoSave
    }
  };
}

export default useAIDriveCanvasIntegration;
