  async analyzeAndTagEmail(email: EmailMessage): Promise<EmailTag[]> {
    const appliedTags: EmailTag[] = [];
    
    // Analyze email content against each rule
    for (const rule of this.taggingRules) {
      const confidence = this.calculateRuleConfidence(email, rule);
      
      if (confidence >= rule.requiredConfidence) {
        const tag: EmailTag = {
          id: `auto-${rule.id}-${email.id}`,
          ...rule.tag,
          confidence,
          autoGenerated: true
        };
        appliedTags.push(tag);
      }
    }

    // Add additional context-based tags
    const contextTags = this.generateContextualTags(email);
    appliedTags.push(...contextTags);

    // Sort by confidence and remove duplicates
    return this.deduplicateTags(appliedTags).sort((a, b) => b.confidence - a.confidence);
  }

  private calculateRuleConfidence(email: EmailMessage, rule: TaggingRule): number {
    let totalMatches = 0;
    let totalChecks = 0;
    
    // Check subject patterns
    if (rule.patterns.subject) {
      totalChecks++;
      const subjectMatches = rule.patterns.subject.some(pattern => 
        pattern.test(email.subject || '')
      );
      if (subjectMatches) totalMatches++;
    }

    // Check from patterns
    if (rule.patterns.from) {
      totalChecks++;
      const fromMatches = rule.patterns.from.some(pattern => 
        pattern.test(email.from || '')
      );
      if (fromMatches) totalMatches++;
    }

    // Check body patterns
    if (rule.patterns.body) {
      totalChecks++;
      const bodyText = email.bodyText || email.bodyHtml || '';
      const bodyMatches = rule.patterns.body.some(pattern => 
        pattern.test(bodyText)
      );
      if (bodyMatches) totalMatches++;
    }

    // Check attachment patterns
    if (rule.patterns.attachments && email.attachments) {
      totalChecks++;
      const attachmentMatches = email.attachments.some(attachment =>
        rule.patterns.attachments!.some(pattern =>
          attachment.filename.toLowerCase().includes(pattern.toLowerCase())
        )
      );
      if (attachmentMatches) totalMatches++;
    }

    return totalChecks > 0 ? totalMatches / totalChecks : 0;
  }

  private generateContextualTags(email: EmailMessage): EmailTag[] {
    const contextTags: EmailTag[] = [];

    // Time-based tags
    const emailDate = new Date(email.date);
    const now = new Date();
    const hoursDiff = (now.getTime() - emailDate.getTime()) / (1000 * 60 * 60);

    if (hoursDiff < 1) {
      contextTags.push({
        id: `time-recent-${email.id}`,
        name: 'Recent',
        category: 'status',
        color: '#10b981',
        confidence: 1.0,
        autoGenerated: true,
        description: 'Received recently'
      });
    }

    // Attachment-based tags
    if (email.attachments && email.attachments.length > 0) {
      contextTags.push({
        id: `has-attachments-${email.id}`,
        name: 'Has Attachments',
        category: 'type',
        color: '#06b6d4',
        confidence: 1.0,
        autoGenerated: true,
        description: `Contains ${email.attachments.length} attachment(s)`
      });
    }

    // Length-based tags
    const bodyLength = (email.bodyText || email.bodyHtml || '').length;
    if (bodyLength > 2000) {
      contextTags.push({
        id: `long-email-${email.id}`,
        name: 'Long Email',
        category: 'type',
        color: '#6b7280',
        confidence: 0.8,
        autoGenerated: true,
        description: 'Lengthy email content'
      });
    }

    return contextTags;
  }

  private deduplicateTags(tags: EmailTag[]): EmailTag[] {
    const uniqueTags = new Map<string, EmailTag>();
    
    for (const tag of tags) {
      const key = `${tag.name}-${tag.category}`;
      const existing = uniqueTags.get(key);
      
      if (!existing || tag.confidence > existing.confidence) {
        uniqueTags.set(key, tag);
      }
    }
    
    return Array.from(uniqueTags.values());
  }

  // Search functionality
  searchEmailsByTags(emails: EmailMessage[], tagNames: string[]): EmailMessage[] {
    return emails.filter(email => {
      if (!email.tags) return false;
      return tagNames.every(tagName =>
        email.tags!.some(tag => 
          tag.name.toLowerCase().includes(tagName.toLowerCase())
        )
      );
    });
  }

  // Get all unique tags from emails
  extractAllTags(emails: EmailMessage[]): EmailTag[] {
    const allTags = new Map<string, EmailTag>();
    
    emails.forEach(email => {
      if (email.tags) {
        email.tags.forEach(tag => {
          allTags.set(tag.id, tag);
        });
      }
    });
    
    return Array.from(allTags.values()).sort((a, b) => a.name.localeCompare(b.name));
  }

  // Get tags by category
  getTagsByCategory(emails: EmailMessage[]): Record<string, EmailTag[]> {
    const allTags = this.extractAllTags(emails);
    const tagsByCategory: Record<string, EmailTag[]> = {};
    
    allTags.forEach(tag => {
      if (!tagsByCategory[tag.category]) {
        tagsByCategory[tag.category] = [];
      }
      tagsByCategory[tag.category].push(tag);
    });
    
    return tagsByCategory;
  }

  // Manual tag management
  createCustomTag(name: string, category: EmailTag['category'], color: string, description?: string): EmailTag {
    return {
      id: `custom-${Date.now()}-${name.toLowerCase().replace(/\s+/g, '-')}`,
      name,
      category,
      color,
      confidence: 1.0,
      autoGenerated: false,
      description
    };
  }

  addTagToEmail(email: EmailMessage, tag: EmailTag): void {
    if (!email.tags) {
      email.tags = [];
    }
    
    // Check if tag already exists
    const existingTag = email.tags.find(t => t.name === tag.name && t.category === tag.category);
    if (!existingTag) {
      email.tags.push(tag);
    }
  }

  removeTagFromEmail(email: EmailMessage, tagId: string): void {
    if (email.tags) {
      email.tags = email.tags.filter(tag => tag.id !== tagId);
    }
  }
