/**
 * Automatically detects the provider preset based on the user's email address domain.
 */
export function detectEmailPreset(email: string): EmailProviderPreset {
  if (!email || !email.includes('@')) {
    return EMAIL_PRESETS.google; // default to google
  }

  const domain = email.split('@')[1]?.toLowerCase().trim() || '';

  // Check known domains
  for (const preset of Object.values(EMAIL_PRESETS)) {
    if (preset.domains.includes(domain)) {
      return preset;
    }
  }

  // Common enterprise / workspace checks
  if (domain.includes('gmail') || domain.includes('google')) {
    return EMAIL_PRESETS.google;
  }
  if (domain.includes('outlook') || domain.includes('office') || domain.includes('microsoft')) {
    return EMAIL_PRESETS.microsoft;
  }
  if (domain.includes('yahoo') || domain.includes('aol')) {
    return EMAIL_PRESETS.yahoo;
  }
  if (domain.includes('icloud') || domain.includes('apple')) {
    return EMAIL_PRESETS.icloud;
  }

  // Fallback to custom for firm/domain specific emails
  return {
    ...EMAIL_PRESETS.custom,
    // Provide sensible smart defaults based on the domain
    imapHost: domain ? `imap.${domain}` : '',
    smtpHost: domain ? `smtp.${domain}` : ''
  };
}
