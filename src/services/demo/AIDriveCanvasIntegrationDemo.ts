/**
 * AI Drive Canvas Integration Demo
 * 
 * Demonstrates the complete flow from chat-generated documents
 * to tabbed document editing in AI Drive.
 */

import { MultiCanvasController, CanvasDocument } from '../../controllers/MultiCanvasController';
import { AIDriveDocumentBridge } from '../bridge/AIDriveDocumentBridge';
import { AIDriveService } from '../drive/aiDriveService';
import { useDocumentTabs } from '../../hooks/useDocumentTabs';

export class AIDriveCanvasIntegrationDemo {
  private multiCanvasController: MultiCanvasController;
  private documentBridge: AIDriveDocumentBridge;

  constructor(
    aiDriveService: AIDriveService,
    documentTabs?: ReturnType<typeof useDocumentTabs>
  ) {
    this.multiCanvasController = new MultiCanvasController();
    this.documentBridge = new AIDriveDocumentBridge(aiDriveService, documentTabs);
  }

  /**
   * Demo: Process a legal consultation chat and create documents
   */
  async demonstrateLegalWorkflow(userId: string, folderId?: string | null) {
    console.log('🎯 Starting AI Drive Canvas Integration Demo');

    // Simulate a legal consultation chat
    const chatConversation = {
      messages: [
        {
          role: 'user',
          content: `I need help with a divorce case. The client is Jane Smith, married for 15 years, 
                   two children aged 12 and 8. They own a house worth $400,000 with a $200,000 mortgage, 
                   and have $150,000 in savings. The husband has been having an affair. 
                   I need to prepare the initial filing documents.`
        },
        {
          role: 'assistant',
          content: `I'll help you prepare the divorce documents for Jane Smith. Based on the information provided, 
                   I'll create several documents: a divorce petition, a property settlement agreement, 
                   a child custody arrangement, and a case strategy memo. Let me prepare these documents now.`
        }
      ]
    };

    // Step 1: Process with MultiCanvasController
    console.log('📝 Processing chat with MultiCanvasController...');
    const canvasResult = await this.multiCanvasController.handleCanvasRequest({
      input: chatConversation.messages[0].content,
      response: chatConversation.messages[1].content,
      conversation: chatConversation,
      userId,
    });

    if (!canvasResult.shouldCreateCanvas) {
      console.log('❌ No documents detected for creation');
      return { success: false, reason: 'No documents detected' };
    }

    console.log(`✅ Detected ${canvasResult.canvases.length} documents to create:`, 
                canvasResult.canvases.map(doc => doc.title));

    // Step 2: Create documents in AI Drive using the bridge
    console.log('💾 Creating documents in AI Drive...');
    const creationResult = await this.documentBridge.createDocumentsFromCanvas({
      documents: canvasResult.canvases,
      userId,
      folderId,
      autoOpen: true,
      source: 'chat'
    });

    console.log('📊 Creation Results:', {
      success: creationResult.success,
      created: creationResult.createdFiles.length,
      errors: creationResult.errors.length
    });

    if (creationResult.createdFiles.length > 0) {
      console.log('📄 Created files:', creationResult.createdFiles.map(f => f.name));
    }

    if (creationResult.errors.length > 0) {
      console.log('❌ Errors:', creationResult.errors);
    }

    return {
      success: creationResult.success,
      canvasDocuments: canvasResult.canvases,
      createdFiles: creationResult.createdFiles,
      errors: creationResult.errors,
      metadata: canvasResult.metadata
    };
  }

  /**
   * Demo: Create a single document manually
   */
  async demonstrateManualDocumentCreation(userId: string, folderId?: string | null) {
    console.log('📝 Demonstrating manual document creation...');

    const result = await this.documentBridge.createSingleDocument(
      userId,
      'Sample Legal Brief',
      `# Legal Brief - Motion to Dismiss

## Case Information
- **Case Number:** CV-2025-001234
- **Court:** Superior Court of California
- **Client:** John Doe
- **Matter:** Motion to Dismiss for Lack of Personal Jurisdiction

## Introduction
This brief is submitted in support of defendant's motion to dismiss...

## Legal Analysis
The court lacks personal jurisdiction over the defendant because...

## Conclusion
For the foregoing reasons, defendant respectfully requests that this Court grant the motion to dismiss.

---
*Generated by AI Drive Document System*`,
      'legal',
      folderId,
      true // auto-open
    );

    console.log('📄 Manual document creation result:', result);
    return result;
  }

  /**
   * Demo: Business document workflow
   */
  async demonstrateBusinessWorkflow(userId: string, folderId?: string | null) {
    console.log('💼 Demonstrating business document workflow...');

    const businessChat = {
      input: `We need to prepare for the Q4 board meeting. Create a board presentation, 
              financial summary, and strategic planning document for next year's initiatives.`,
      response: `I'll create a comprehensive board meeting package including a presentation deck, 
                financial analysis, and strategic planning document for your Q4 board meeting.`,
      conversation: { messages: [] },
      userId
    };

    const result = await this.multiCanvasController.handleCanvasRequest(businessChat);
    
    if (result.shouldCreateCanvas) {
      const creationResult = await this.documentBridge.createDocumentsFromCanvas({
        documents: result.canvases,
        userId,
        folderId,
        autoOpen: false, // Don't auto-open all business docs
        source: 'chat'
      });

      return {
        success: creationResult.success,
        documents: result.canvases,
        files: creationResult.createdFiles
      };
    }

    return { success: false, reason: 'No business documents detected' };
  }

  /**
   * Update the document tabs reference
   */
  updateDocumentTabs(documentTabs: ReturnType<typeof useDocumentTabs>) {
    this.documentBridge.setDocumentTabs(documentTabs);
  }

  /**
   * Get integration statistics
   */
  getIntegrationStats() {
    return {
      demoName: 'AI Drive Canvas Integration',
      version: '1.0.0',
      features: [
        'Chat-to-Document Generation',
        'Automatic AI Drive Storage',
        'Tabbed Document Editing',
        'Multi-Document Workflows',
        'Legal & Business Templates'
      ],
      supportedDocumentTypes: [
        'Legal Petitions',
        'Business Reports',
        'Contracts & Agreements',
        'Strategy Documents',
        'Correspondence'
      ]
    };
  }
}

/**
 * Factory function to create the demo with services
 */
export function createAIDriveCanvasDemo(
  aiDriveService: AIDriveService,
  documentTabs?: ReturnType<typeof useDocumentTabs>
): AIDriveCanvasIntegrationDemo {
  return new AIDriveCanvasIntegrationDemo(aiDriveService, documentTabs);
}
