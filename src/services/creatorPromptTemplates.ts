// 🚀 AUTO-SUGGESTIONS BASED ON INPUT
export const getTemplatesByInput = (userInput: string) => {
  const input = userInput.toLowerCase();
  
  if (input.includes('viral') || input.includes('trending')) {
    return [creatorPromptTemplates.viralPostGenerator, creatorPromptTemplates.trendHijacker];
  }
  
  if (input.includes('week') || input.includes('plan')) {
    return [creatorPromptTemplates.weeklyDomination, creatorPromptTemplates.contentMultiplier];
  }
  
  if (input.includes('money') || input.includes('monetize')) {
    return [creatorPromptTemplates.sponsorshipReadyPost, creatorPromptTemplates.affiliateContentTemplate];
  }
  
  if (input.includes('tiktok')) {
    return [creatorPromptTemplates.tiktokViralFormula, creatorPromptTemplates.voiceOverScript];
  }
  
  if (input.includes('instagram')) {
    return [creatorPromptTemplates.instagramReelsMagic, creatorPromptTemplates.carouselMaster];
  }
  
  // Default suggestions
  return [creatorPromptTemplates.viralPostGenerator, creatorPromptTemplates.weeklyDomination];
};

