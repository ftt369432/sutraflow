  private extractRequiredIntegrations(steps: WorkflowStep[]): string[] {
    const integrations = new Set<string>();
    
    for (const step of steps) {
      if (step.systemType === AgentSystemType.N8N_WORKFLOW) {
        integrations.add('n8n');
      }
      if (step.systemType === AgentSystemType.EMAIL) {
        integrations.add('email');
      }
      // Add more integration detection logic
    }

    return Array.from(integrations);
  }

  /**
   * 📝 Generate workflow name from description
   */
  private generateWorkflowName(description: string): string {
    // Extract key action words
    const actionWords = description.match(/\b(create|generate|process|send|sync|build|automate)\b/gi) || ['create'];
    const objectWords = description.match(/\b(lead|email|content|data|workflow|agent)\b/gi) || ['workflow'];
    
    const action = actionWords[0];
    const object = objectWords[objectWords.length - 1];
    
    return `${action} ${object} workflow`.replace(/\b\w/g, l => l.toUpperCase());
  }

