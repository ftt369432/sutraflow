  /**
   * 🎯 Main Auto-Builder Method
   * Convert natural language to complete workflow
   */
  async autoGenerateWorkflow(description: string, context?: any): Promise<AutoGeneratedWorkflow> {
    console.log('🤖 Auto-generating workflow from:', description);

    // 1. Parse the description to identify patterns
    const detectedPatterns = this.parseWorkflowDescription(description);
    
    // 2. Select best workflow pattern
    const primaryPattern = this.selectPrimaryPattern(detectedPatterns);
    
    // 3. Generate workflow steps
    const steps = await this.generateWorkflowSteps(primaryPattern, description, detectedPatterns);
    
    // 4. Create n8n template if needed
    const n8nTemplate = this.generateN8nTemplate(primaryPattern, steps);
    
    // 5. Assemble complete workflow
    const workflow: AutoGeneratedWorkflow = {
      id: `auto_${Date.now()}`,
      name: this.generateWorkflowName(description),
      description: `Auto-generated workflow: ${description}`,
      steps,
      triggers: this.generateTriggers(primaryPattern),
      estimatedTime: this.calculateEstimatedTime(steps),
      complexity: this.workflowPatterns[primaryPattern]?.complexity || 'medium',
      requiredIntegrations: this.extractRequiredIntegrations(steps),
      n8nTemplate
    };

    console.log('✅ Auto-generated workflow:', workflow);
    return workflow;
  }

  /**
   * 🔍 Parse description to detect workflow patterns
   */
  private parseWorkflowDescription(description: string): string[] {
    const words = description.toLowerCase().split(/\s+/);
    const detectedPatterns: string[] = [];

    for (const word of words) {
      for (const [keyword, pattern] of Object.entries(this.keywordPatterns)) {
        if (word.includes(keyword) && !detectedPatterns.includes(pattern)) {
          detectedPatterns.push(pattern);
        }
      }
    }

    // If no patterns detected, default to content creation
    return detectedPatterns.length > 0 ? detectedPatterns : ['content_creation'];
  }

  /**
   * 🎯 Select the primary workflow pattern
   */
  private selectPrimaryPattern(detectedPatterns: string[]): string {
    if (detectedPatterns.length === 1) {
      return detectedPatterns[0];
    }

    // Priority order for multiple patterns
    const priorities = [
      'lead_generation',
      'customer_onboarding', 
      'crm_integration',
      'email_automation',
      'data_processing',
      'content_creation',
      'social_media',
      'document_workflow'
    ];

    for (const priority of priorities) {
      if (detectedPatterns.includes(priority)) {
        return priority;
      }
    }

    return detectedPatterns[0];
  }

  /**
   * 🔨 Generate workflow steps based on pattern
   */
  private async generateWorkflowSteps(
    primaryPattern: string, 
    description: string, 
    allPatterns: string[]
  ): Promise<WorkflowStep[]> {
    const pattern = this.workflowPatterns[primaryPattern];
    if (!pattern) {
      throw new Error(`Unknown workflow pattern: ${primaryPattern}`);
    }

    const steps: WorkflowStep[] = [];
    let stepIndex = 1;

    // Generate steps for primary pattern
    for (const agentType of pattern.agents) {
      const step: WorkflowStep = {
        id: `step_${stepIndex}`,
        name: this.generateStepName(agentType, primaryPattern),
        agentType,
        systemType: this.mapAgentTypeToSystem(agentType),
        inputs: this.generateStepInputs(agentType, primaryPattern),
        outputs: this.generateStepOutputs(agentType),
        nextSteps: stepIndex < pattern.agents.length ? [`step_${stepIndex + 1}`] : []
      };
      steps.push(step);
      stepIndex++;
    }

    // Add integration steps for additional patterns
    for (const additionalPattern of allPatterns) {
      if (additionalPattern !== primaryPattern) {
        const integrationStep = this.generateIntegrationStep(additionalPattern, stepIndex);
        if (integrationStep) {
          steps.push(integrationStep);
          stepIndex++;
        }
      }
    }

    return steps;
  }

