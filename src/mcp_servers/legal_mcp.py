def _get_cached_manifest():
    if not os.path.exists(MANIFEST_PATH):
        return None
    try:
        mtime = os.path.getmtime(MANIFEST_PATH)
        if _CACHE["manifest"] is not None and _CACHE["manifest_mtime"] == mtime:
            return _CACHE["manifest"]
        with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        _CACHE["manifest"] = data
        _CACHE["manifest_mtime"] = mtime
        return data
    except Exception:
        return None

def _get_cached_suite_data():
    if not os.path.exists(SUITE_DATA_PATH):
        return None
    try:
        mtime = os.path.getmtime(SUITE_DATA_PATH)
        if _CACHE["suite_data"] is not None and _CACHE["suite_data_mtime"] == mtime:
            return _CACHE["suite_data"]
        with open(SUITE_DATA_PATH, "r", encoding="utf-8") as f:
            raw_js = f.read().strip()
        if raw_js.startswith("window.SUITE_DATA = "):
            raw_js = raw_js[len("window.SUITE_DATA = "):]
        if raw_js.endswith(";"):
            raw_js = raw_js[:-1]
        data = json.loads(raw_js)
        _CACHE["suite_data"] = data
        _CACHE["suite_data_mtime"] = mtime
        return data
    except Exception:
        return None



